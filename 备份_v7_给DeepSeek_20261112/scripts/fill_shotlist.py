# renumber: shot i uses table row i (1..71); row 72 folded into 71's tail per alignment check
rows = []
with open(WORK / "shotlist.csv", encoding="utf-8-sig") as f:
    rd = list(csv.reader(f))
hdr, body = rd[0], rd[1:]
assert len(body) == 71

for r in body:
    i = int(r[0][1:])
    size, action, move, dial, src = T[i]
    r[5], r[6], r[7], r[8], r[9] = size, action, move, dial, src
    r[10] = "pending"
    rows.append(r)

with open(WORK / "shotlist.csv", "w", newline="", encoding="utf-8-sig") as f:
    w = csv.writer(f)
    w.writerow(hdr)
    w.writerows(rows)

# re-extract frames with accurate seek (-ss after -i)
for r in rows:
    i, fs = int(r[0][1:]), int(r[1])
    t = (fs - 1) / FPS + min(0.35, 0.4 * int(r[3]) / FPS)
    out = SHOTS / f"S{i:03d}_frame.jpg"
    subprocess.run([FFMPEG, "-hide_banner", "-loglevel", "error", "-i", VIDEO,
                    "-ss", f"{t:.3f}", "-frames:v", "1", "-q:v", "2", "-y", str(out)],
                   check=True)
print("shotlist filled:", len(rows), "rows; frames re-extracted accurately")
empty_status = [r[0] for r in rows if not r[10]]
empty_action = [r[0] for r in rows if not r[6]]
